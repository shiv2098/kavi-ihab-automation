"""Optional local Kokoro-82M narration generator.

IMPORTANT RIGHTS GATE:
The official model card labels the weights Apache-2.0, but it does not identify the
training-data provenance separately for each built-in voice. It also says the dataset
includes synthetic audio generated by closed TTS systems. Do not publish a voice output
on a monetized channel until the specific voice's provenance/rights have been confirmed
with the model maintainers or your rights reviewer. This script is supplied for local
audition only; no narration was generated in this run.

Free local setup (no paid API):
  python -m venv .venv
  source .venv/bin/activate
  pip install 'kokoro>=0.9.2' soundfile numpy
  # Install espeak-ng using your OS package manager if required by the English G2P stack.
  python generate_kokoro_AUDITION_ONLY.py

Voice preference: am_michael (American English male; voice-level provenance still needs confirmation).
"""
from pathlib import Path
import numpy as np
import soundfile as sf
from kokoro import KPipeline

TEXT = (Path(__file__).resolve().parents[1] / 'script_final_135_words.txt').read_text(encoding='utf-8').strip()
OUT = Path(__file__).with_name('voiceover_kokoro_AUDITION_ONLY.wav')
pipeline = KPipeline(lang_code='a')
chunks = []
for _, _, audio in pipeline(TEXT, voice='am_michael'):
    chunks.append(np.asarray(audio, dtype=np.float32))
if not chunks:
    raise RuntimeError('Kokoro returned no audio chunks')
audio = np.concatenate(chunks)
sf.write(OUT, audio, 24000)
print(f'Wrote {OUT} — audition only; do not publish until voice rights are cleared.')
